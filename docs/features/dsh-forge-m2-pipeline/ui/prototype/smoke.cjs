/* M2 UI 原型冒烟(v9 = R1-R7 全修 + 子tab 提案|feature|任务) */
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require(path.resolve(__dirname, '../../../../../node_modules/@playwright/test'))

const EXE = 'C:/Users/panda/AppData/Local/ms-playwright/chromium-1217/chrome-win64/chrome.exe'
let pass = 0, fail = 0
const ok = (cond, name) => { if (cond) { pass++; console.log('  ✓ ' + name) } else { fail++; console.log('  ✗ ' + name) } }
const rowOf = (page, id) => page.locator('.task-row').filter({ has: page.locator(`.task-id:text-is("${id}")`) })

;(async () => {
  const browser = await chromium.launch(fs.existsSync(EXE) ? { executablePath: EXE } : {})
  const page = await (await browser.newContext()).newPage()
  const errors = []
  page.on('pageerror', (e) => errors.push(String(e)))
  await page.goto('file:///' + path.join(__dirname, 'index.html').replace(/\\/g, '/'))
  await page.waitForSelector('.app-frame')
  await page.locator('[data-act="proto-collapse"]').click()
  await page.locator('#btn-rightbar').click()
  const firstGuideTitle = await page.locator('.dsw-guide-entry .entry-title').first().textContent()
  ok(firstGuideTitle.includes('项目概览'), '开始页排序:项目概览在最上面')
  await page.locator('.dsw-guide-entry[data-sidebar-right-guide-entry="dswf-overview"]').click()

  console.log('— P4:ov-head 折叠 + 子tab 顺序(提案|feature|任务) + sticky —')
  ok(await page.locator('.ov-status-line').count() === 1, '状态摘要行(一行)')
  ok(await page.locator('.ov-info').count() === 0, '路径默认折叠')
  await page.locator('[data-act="ov-head-toggle"]').click()
  ok(await page.locator('.ov-info').count() === 1, '▾ 展开位置详情')
  const infoKs = await page.locator('.ov-info-k').allTextContents()
  ok(infoKs.includes('工作区'), '含「工作区」行')
  await page.locator('[data-act="ov-head-toggle"]').click()
  const tabs = await page.locator('.ov-subtab').allTextContents()
  ok(tabs.join('|') === '提案|feature|任务', '子tab 顺序:提案|feature|任务(用户定向)')
  ok(await page.locator('.ov-sticky').count() === 1, 'sticky 区')

  console.log('— 排序切换 —')
  ok(await page.locator('.ov-sort-pill').count() === 1, '排序切换钮在场')
  const sortLabel1 = await page.locator('.ov-sort-pill').textContent()
  ok(sortLabel1.includes('活跃优先'), '默认排序 = 活跃优先')
  /* 切到最新创建 */
  await page.locator('.ov-sort-pill').click()
  const sortLabel2 = await page.locator('.ov-sort-pill').textContent()
  ok(sortLabel2.includes('最新创建'), '切换后 = 最新创建')
  /* 提案按创建时间排序:demo-ui-polish(10-04)应排最前 */
  const firstProp = await page.locator('.ov-parent .ellipsis').first().textContent()
  ok(firstProp.includes('打磨') || firstProp.includes('polish'), '最新创建:10-04 的提案排最前(' + firstProp + ')')
  /* 切回活跃优先 */
  await page.locator('.ov-sort-pill').click()
  const sortLabel3 = await page.locator('.ov-sort-pill').textContent()
  ok(sortLabel3.includes('活跃优先'), '切回 = 活跃优先')
  /* 活跃排序:评审中的提案排最前 */
  const firstPropActive = await page.locator('.ov-parent .ellipsis').first().textContent()
  ok(firstPropActive.includes('打磨') || firstPropActive.includes('polish'), '活跃优先:评审中的排最前(' + firstPropActive + ')')

  console.log('— R5:提案/feature 状态中文 —')
  const propChips = await page.locator('.ov-parent .chip').allTextContents()
  ok(propChips.some(c => c.includes('已接受') || c.includes('评审中')), '提案状态中文(R5):' + propChips.join(','))
  await page.locator('.ov-parent').first().click()
  ok(await page.locator('.m2-task-detail .tl-row').count() >= 5, '提案行展开元数据')
  await page.locator('.ov-subtab', { hasText: 'feature' }).click()
  const featChips = await page.locator('.ov-parent .chip').allTextContents()
  ok(featChips.some(c => c.includes('进行中') || c.includes('任务')), 'feature 状态中文(R5):' + featChips.join(','))

  console.log('— P3:文档行整行可点 → dock 新 tab(非抽屉) —')
  const doc = page.locator('.ov-doc').first()
  ok(await doc.getAttribute('data-act') === 'doc-open', '整行 data-act=doc-open')
  await doc.click()
  ok(await page.locator('.rb-chip.active').count() === 1, '文档点击 → dock 新 tab(P3:非抽屉)')
  ok(await page.locator('.doc-tab-body h1').count() >= 1, 'tab 内 Markdown 渲染(h1)')
  ok(await page.locator('.mermaid-card').count() >= 1, 'mermaid 代码块 → 占位卡(Diagram 标注 + 源码 + 扩展点说明)')
  ok(await page.locator('.mermaid-card .mc-note').count() >= 1, 'mermaid 占位含「产品扩展点」注记')
  /* 同文档重开 = 激活已有 tab(去重) */
  const tabCount1 = await page.locator('.rb-chip').count()
  await page.locator('.rb-chip', { hasText: '项目概览' }).click()
  await page.locator('.ov-doc').first().click()
  const tabCount2 = await page.locator('.rb-chip').count()
  ok(tabCount1 === tabCount2, '同文档重开 = 激活已有 tab(去重,不新开)')
  /* 关闭文档 tab */
  await page.locator('.rb-chip', { hasText: 'prd-spec.md' }).first().locator('.chip-x').click()
  ok(await page.locator('.dsw-guide, .ov-parent').first().isVisible(), '关闭文档 tab → 回概览或开始页')

  console.log('— 任务子tab:两行布局 + 任务详情抽屉 —')
  await page.locator('.ov-subtab', { hasText: '任务' }).click()
  ok(await page.locator('.task-item').count() === 11, '任务行 ×11')
  ok(await page.locator('.task-sub').count() === 11, '副行 ×11')
  ok(await page.locator('.status-tag', { hasText: '执行中' }).count() >= 1, '状态 tag 中文')
  await rowOf(page, 'fix-1').first().click()
  ok(await page.locator('.task-drawer').count() === 1, 'fix 任务点击 → 抽屉(模块化)')
  ok(await page.locator('.task-drawer .menu-label', { hasText: 'Fix 链' }).count() === 1, 'fix 类型 → Fix 链区块(来源/根因/源文件)')
  ok(await page.locator('.task-drawer .tl-note', { hasText: 'validator' }).count() >= 1, 'Fix 链含根因描述')
  await page.keyboard.press('Escape')
  await rowOf(page, '2.4').first().click()
  ok(await page.locator('.task-drawer .menu-label', { hasText: '覆盖率' }).count() === 1, 'coding.feature → 覆盖率区块(进度条)')
  await page.keyboard.press('Escape')
  await rowOf(page, '2.5').first().click()
  ok(await page.locator('.task-drawer .menu-label', { hasText: '阻塞原因' }).count() === 1, 'blocked 任务 → 阻塞原因区块')
  await page.keyboard.press('Escape')
  await rowOf(page, '2.10').first().click()
  ok(await page.locator('.task-drawer .menu-label', { hasText: '质量门' }).count() === 1, 'gate 类型 → 质量门检查区块')
  ok(await page.locator('.task-drawer .tl-verb', { hasText: '2.5' }).count() >= 1, 'gate 前置依赖含 2.5')
  await page.keyboard.press('Escape')
  /* 搜索 */
  await page.fill('#ov-q', '执行中')
  ok(await page.locator('.task-item').count() >= 1, '搜索「执行中」→ 有结果(R2)')
  await page.fill('#ov-q', 'pending')
  ok(await page.locator('.task-item').count() >= 3, '搜索「pending」→ 英文也匹配')
  await page.locator('[data-act="ov-q-clear"]').click()

  console.log('— R5:DAG(箭头方向修复) + 泳道(空列折叠) + chips 三视图 —')
  await page.locator('.task-viewseg .seg-btn', { hasText: 'DAG' }).click()
  ok(await page.locator('.dag-svg marker').count() >= 1, 'DAG 箭头 marker')
  const legend = await page.locator('.dag-legend').textContent()
  ok(legend.includes('后续'), '图例「箭头指向后续任务」(R2 修复)')
  await page.locator('.dag-node').first().click()
  ok(await page.locator('.task-drawer').count() === 1, 'DAG 节点点击 → 抽屉打开')
  await page.keyboard.press('Escape')
  await page.locator('.task-viewseg .seg-btn', { hasText: '泳道' }).click()
  ok(await page.locator('.swim-col-empty').count() >= 1, '0 计数列折叠')
  await page.locator('.task-viewseg .seg-btn', { hasText: '列表' }).click()

  console.log('— R7:0 计数 chip 禁用 + 转移菜单全七态 —')
  const zeroChip = page.locator('.st-chip.is-zero').first()
  ok(await zeroChip.getAttribute('disabled') !== null, '0 计数 chip disabled(R7)')
  const row26 = rowOf(page, '2.6')
  await row26.hover()
  await row26.locator('[data-act="task-more"]').click()
  const menuItems = await page.locator('.menu-item').allTextContents()
  const transItems = menuItems.filter(m => m.startsWith('转 '))
  ok(transItems.length === 6, '转移菜单全六态(当前 suspended 除外,R7 修复 slice)')
  await page.keyboard.press('Escape')
  await page.keyboard.press('Escape')

  console.log('— R1:派发链 → 概览即时刷新 —')
  await page.locator('.sess-row', { hasText: 'run-tasks' }).first().click()
  /* 先打开概览 tab 使其激活 */
  await page.locator('.rb-chip', { hasText: '项目概览' }).click()
  await page.locator('.ov-subtab', { hasText: '任务' }).click()
  await page.locator('#composer-input').click()
  await page.keyboard.insertText('跑任务')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(5600)
  ok(await rowOf(page, '2.4').locator('.status-tag.st-completed').count() === 1, '2.4 → completed(R1 修复:概览即时刷新)')

  console.log('— R3:ov-row-more 菜单 —')
  await page.locator('.ov-subtab', { hasText: '提案' }).click()
  await page.locator('.ov-parent').first().hover()
  await page.locator('[data-act="ov-row-more"]').first().click()
  ok(await page.locator('.menu-item').count() >= 2, 'ov-row-more 有真菜单(R3)')
  await page.keyboard.press('Escape')

  console.log('— 回归 —')
  ok(errors.length === 0, '零页面 JS 错误' + (errors.length ? ':' + errors.join(' | ') : ''))

  await browser.close()
  console.log(`\n结果:${pass} 通过 / ${fail} 失败`)
  process.exit(fail ? 1 : 0)
})().catch((e) => { console.error(e); process.exit(1) })
