// forge remote 生成物完整性钉（typert strict 迁移 1.5——双表 pin 测试族退役）：
// 手写 descriptor 表已退役，client 贡献 = 官方 generator 产出的 Host-for-Client Remote
// 投影（dist/typert.remote-client.js 的 TYPERT_REMOTE）。本钉锁定「生成物在场 + 完整 +
// 契约命名」，取代旧「client 表 ↔ host marker 表」双表 pin——两半同源生成，漂移在
// 构建期 generator 强校验面消灭，测试只钉产物本体。
// 运行前提：pnpm -C plugins/project build（工件由 generate-typert.mjs 生成步入 dist）。
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'
import type { InvocationDescriptor } from '@deepseek-ai/dsh-typert-protocol'
import { FORGE_REMOTE_CONTRIBUTION } from './remote.js'

const pkgRoot = fileURLToPath(new URL('..', import.meta.url))
const pkg = JSON.parse(readFileSync(`${pkgRoot}package.json`, 'utf8')) as {
  exports: Record<string, { types?: string; default?: string }>
  files: string[]
}

describe('forge remote 生成物完整性钉（client 半 = ./remote 生成投影）', () => {
  it('导出契约钉：./typert + ./remote 精确映射官方三件套命名工件（勿自造）', () => {
    expect(pkg.exports['./typert']).toEqual({ types: './dist/typert.host.d.ts', default: './dist/typert.host.js' })
    expect(pkg.exports['./remote']).toEqual({ types: './dist/typert.remote-client.d.ts', default: './dist/typert.remote-client.js' })
    for (const rel of ['dist/typert.host.js', 'dist/typert.host.d.ts', 'dist/typert.remote-client.js', 'dist/typert.remote-client.d.ts']) {
      expect(() => readFileSync(`${pkgRoot}${rel}`, 'utf8'), `${rel} 在场`).not.toThrow()
      expect(pkg.files, `${rel} 入 files 清单`).toContain(rel)
    }
  })

  it('生成器出厂数记：remote-client 工件带 generator 出厂头（非手写）', () => {
    const js = readFileSync(`${pkgRoot}dist/typert.remote-client.js`, 'utf8')
    expect(js).toContain('Generated by @deepseek-ai/dsh-typert-generator')
    expect(js).toContain('export const TYPERT_REMOTE')
    const dts = readFileSync(`${pkgRoot}dist/typert.remote-client.d.ts`, 'utf8')
    expect(dts).toContain('Generated by @deepseek-ai/dsh-typert-generator')
  })

  it('贡献本体：package = 本包名 + descriptors 非空 + 端点 id 全局唯一', () => {
    expect(FORGE_REMOTE_CONTRIBUTION.package).toBe('@dsh-forge/project')
    const descriptors = FORGE_REMOTE_CONTRIBUTION.descriptors as readonly InvocationDescriptor[]
    expect(descriptors.length).toBeGreaterThan(0)
    const ids = descriptors.map((d) => d.id)
    expect(new Set(ids).size).toBe(ids.length)
    for (const id of ids) expect(id.startsWith('@dsh-forge/project#'), id).toBe(true)
  })

  it('descriptor 形状：cancellation=signal 全量 + codec strict + zod 工厂在座（生成物锁定）', () => {
    const descriptors = FORGE_REMOTE_CONTRIBUTION.descriptors as readonly InvocationDescriptor[]
    for (const d of descriptors) {
      expect(d.cancellation, `${d.namespace}/${d.method}`).toEqual({ parameter: 'signal' })
      expect(d.invocation).toEqual({ kind: 'direct' })
      expect(d.service.endsWith('Controller'), `${d.namespace}/${d.method} service 键`).toBe(true)
      for (const p of d.parameters) {
        expect(p.source).toBe('json')
        expect(p.codec.mode, `${d.namespace}/${d.method}.${p.wire}`).toBe('strict')
        expect(typeof p.codec.create, `${d.namespace}/${d.method}.${p.wire} codec 工厂`).toBe('function')
      }
      expect(d.result.mode, `${d.namespace}/${d.method} result codec`).toBe('strict')
      expect(typeof d.result.create, `${d.namespace}/${d.method} result 工厂`).toBe('function')
    }
  })

  it('端点边 pin（生成物 ↔ 六族消费切片锚点）：stream 别名与 query wire 名由生成物锁定', () => {
    const descriptors = FORGE_REMOTE_CONTRIBUTION.descriptors as readonly InvocationDescriptor[]
    const endpoint = (ns: string, method: string): InvocationDescriptor => {
      const hit = descriptors.find((d) => d.namespace === ns && d.method === method)
      expect(hit, `${ns}/${method} 在生成物中`).toBeTruthy()
      return hit!
    }
    expect(endpoint('forgeWorktree', 'followSeal').mode).toBe('stream')
    expect(endpoint('forgeWorktree', 'delete').implementation).toBe('remove')
    expect(endpoint('forgeWorktree', 'list').parameters.map((p) => p.wire)).toEqual(['query'])
    expect(endpoint('forgeBugs', 'list').parameters.map((p) => p.wire)).toEqual(['query'])
    expect(endpoint('forgeProjects', 'list').parameters).toEqual([])
    expect(endpoint('forgeDirs', 'facts').parameters.map((p) => p.wire)).toEqual(['query'])
  })
})
