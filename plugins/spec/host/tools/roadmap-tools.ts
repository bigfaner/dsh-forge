// roadmap 族 tools（plugin-spec-roadmaps 1.8，tools.md §一 Roadmap 族逐行）——薄封装：
// 域逻辑单一事实源 = tool-service 组合根（roadmap-service 动词零域重复）。入参纪律：
// 零 projectKey（cwd 派生）/ 零 actor（对话 tool 径 = plugin-tool 注入）。
import {
  callToolFace,
  formatFailure,
  formatOk,
  isForgeToolFailure,
  optionalString,
  requireArgsObject,
  requiredEnum,
  requiredString,
  withFailureVariant,
} from "@dsh-forge/lib-api";
import type { MilestoneRow, ObjectiveStatus, RoadmapRow } from "../db/row-types.js";
import { OBJECTIVE_STATUSES, ROADMAP_STATES } from "../domain/status-machines.js";
import type { ForgeToolServices } from "../domain/specs/tool-service.js";
import { requireSessionCwd, type SpecToolDefinition, type SpecToolExecFace } from "./faces.js";
import { optionalAcEntries, optionalStringArrayField, optionalStringField } from "./parse-fields.js";

/** 合法边描述（roadmapMachine 边表单源展开——human-only/noteRequired 元数据随边标注）。 */
const EDGE_DESC = OBJECTIVE_STATUSES.flatMap((from) => {
  const def = ROADMAP_STATES.states[from];
  const edges = "edges" in def ? (def.edges as Partial<Record<ObjectiveStatus, { humanOnly?: boolean; noteRequired?: boolean }>>) : undefined;
  return def.targets.map((to) => {
    const meta = edges?.[to];
    const tag = meta?.humanOnly ? " (human-only — only on explicit user acceptance)" : meta?.noteRequired ? " (note required)" : "";
    return `${from}→${to}${tag}`;
  });
}).join(", ");

// ── create_roadmap ──

export function createCreateRoadmapTool(verbs: ForgeToolServices): SpecToolDefinition {
  const TOOL = "create_roadmap";
  return {
    name: TOOL,
    description:
      "Create a roadmap (top-level goal container): slug/title/brief plus optional product-level AC entries (ac_json; entry ids are generated by the service). Starts in pending; starts when its first milestone is created.",
    parameters: {
      type: "object",
      properties: {
        slug: { type: "string", description: "Roadmap slug (unique per project)." },
        title: { type: "string", description: "Roadmap title." },
        brief: { type: "string", description: "Optional brief." },
        ac_json: { type: "array", items: { type: "object" }, description: "Optional product AC entries: [{criterion, id?}] (ids generated server-side when omitted)." },
      },
      required: ["slug", "title"],
    },
    output: {
      schema: withFailureVariant({ type: "object", additionalProperties: false, properties: { roadmap: { type: "object", description: "Roadmap snapshot row." } }, required: ["roadmap"] }),
      render(_a, value) {
        if (isForgeToolFailure(value)) return formatFailure(value);
        const v = value as { roadmap: RoadmapRow };
        return formatOk(`roadmap created: ${v.roadmap.slug} [${v.roadmap.roadmapStatus}]`, roadmapLines(v.roadmap));
      },
    },
    async execute(args: unknown, exec: SpecToolExecFace) {
      return callToolFace(async () => {
        const a = requireArgsObject(args, TOOL);
        const acEntries = optionalAcEntries(a, TOOL);
        return {
          roadmap: verbs.createRoadmap({
            cwd: requireSessionCwd(exec),
            slug: requiredString(a, "slug", TOOL),
            title: requiredString(a, "title", TOOL),
            ...(optionalStringField(a, "brief") !== undefined ? { brief: optionalStringField(a, "brief")! } : {}),
            ...(acEntries !== undefined ? { acEntries } : {}),
          }),
        };
      });
    },
  };
}

