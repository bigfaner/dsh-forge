// ── transition_roadmap ──

export function createTransitionRoadmapTool(verbs: ForgeToolServices): SpecToolDefinition {
  const TOOL = "transition_roadmap";
  return {
    name: TOOL,
    description:
      `Transition a roadmap along its state machine (legal edges: ${EDGE_DESC}). awaiting_acceptance→completed is human-only — call it only on an explicit user acceptance decision; the return edge (awaiting_acceptance→in_progress) requires a note. Actor is fixed to the conversation tool channel — never fabricate an actor parameter.`,
    parameters: {
      type: "object",
      properties: {
        roadmap_slug: { type: "string", description: "Roadmap slug (path resolution = roadmap_slug + milestone_id)." },
        to: { type: "string", description: `Target status: ${OBJECTIVE_STATUSES.join(" | ")}. Legal edges: ${EDGE_DESC}.` },
        note: { type: "string", description: "Transition note; REQUIRED on the return edge (awaiting_acceptance → in_progress)." },
      },
      required: ["roadmap_slug", "to"],
    },
    output: {
      schema: withFailureVariant({ type: "object", additionalProperties: false, properties: { roadmap: { type: "object", description: "Transitioned roadmap snapshot row." } }, required: ["roadmap"] }),
      render(_a, value) {
        if (isForgeToolFailure(value)) return formatFailure(value);
        const v = value as { roadmap: RoadmapRow };
        return formatOk(`roadmap transitioned: ${v.roadmap.slug} → [${v.roadmap.roadmapStatus}]`, roadmapLines(v.roadmap));
      },
    },
    async execute(args: unknown, exec: SpecToolExecFace) {
      return callToolFace(async () => {
        const a = requireArgsObject(args, TOOL);
        return {
          roadmap: verbs.transitionRoadmap({
            cwd: requireSessionCwd(exec),
            roadmapSlug: requiredString(a, "roadmap_slug", TOOL),
            to: requiredEnum<ObjectiveStatus>(a, "to", OBJECTIVE_STATUSES, TOOL),
            ...(optionalString(a, "note", TOOL) !== undefined ? { note: optionalString(a, "note", TOOL)! } : {}),
          }),
        };
      });
    },
  };
}

// ── query_roadmap ──

export function createQueryRoadmapTool(verbs: ForgeToolServices): SpecToolDefinition {
  const TOOL = "query_roadmap";
  return {
    name: TOOL,
    description:
      "Query one roadmap: snapshot + milestones (seq order, ids carried). include=['achievement'] adds the derived achievement DTO (perMilestone drill-down + zero-carrier warns, computed live — never stored).",
    parameters: {
      type: "object",
      properties: {
        slug: { type: "string", description: "Roadmap slug." },
        include: { type: "array", items: { type: "string" }, description: "Optional expansions, closed set: achievement. Unknown values are rejected." },
      },
      required: ["slug"],
    },
    output: {
      schema: withFailureVariant({
        type: "object",
        additionalProperties: false,
        properties: {
          roadmap: { type: "object", description: "Roadmap snapshot row." },
          milestones: { type: "array", items: { type: "object" }, description: "Milestone cards (seq order; milestoneId always carried)." },
          achievement: { type: "object", description: "Derived achievement DTO (when included): completed + perMilestone + warns." },
        },
        required: ["roadmap", "milestones"],
      }),
      render(_a, value) {
        if (isForgeToolFailure(value)) return formatFailure(value);
        const v = value as { roadmap: RoadmapRow; milestones: MilestoneRow[]; achievement?: { completed: boolean } };
        const lines = [
          `✓ roadmap ${v.roadmap.slug} [${v.roadmap.roadmapStatus}]`,
          `- milestones: ${v.milestones.length}`,
          ...v.milestones.map((m) => `  - #${m.seq} ${m.title} [${m.milestoneStatus}] id=${m.id}`),
          ...(v.achievement !== undefined ? [`- achievement: ${v.achievement.completed ? "completed" : "in progress"}`] : []),
        ];
        return formatOk(`roadmap ${v.roadmap.slug}`, lines.slice(1));
      },
    },
    async execute(args: unknown, exec: SpecToolExecFace) {
      return callToolFace(async () => {
        const a = requireArgsObject(args, TOOL);
        return verbs.queryRoadmap({
          cwd: requireSessionCwd(exec),
          slug: requiredString(a, "slug", TOOL),
          include: optionalStringArrayField(a, "include"),
        });
      });
    },
  };
}

// ── list_roadmaps ──

export function createListRoadmapsTool(verbs: ForgeToolServices): SpecToolDefinition {
  const TOOL = "list_roadmaps";
  return {
    name: TOOL,
    description: "List roadmaps of the current project (listing index order). Read-only; no parameters.",
    parameters: { type: "object", properties: {} },
    output: {
      schema: withFailureVariant({ type: "object", additionalProperties: false, properties: { roadmaps: { type: "array", items: { type: "object" }, description: "Roadmap snapshot rows (listing index order)." } }, required: ["roadmaps"] }),
      render(_a, value) {
        if (isForgeToolFailure(value)) return formatFailure(value);
        const v = value as { roadmaps: RoadmapRow[] };
        return formatOk(`${v.roadmaps.length} roadmap(s)`, v.roadmaps.map((r) => `- ${r.slug} [${r.roadmapStatus}] ${r.title}`));
      },
    },
    async execute(args: unknown, exec: SpecToolExecFace) {
      return callToolFace(async () => {
        requireArgsObject(args, TOOL);
        return { roadmaps: verbs.listRoadmaps({ cwd: requireSessionCwd(exec) }) };
      });
    },
  };
}

/** roadmap 快照键值行（写动词共用投影）。 */
export function roadmapLines(roadmap: RoadmapRow): string[] {
  return [
    `- slug: ${roadmap.slug}`,
    `- title: ${roadmap.title}`,
    `- status: ${roadmap.roadmapStatus}`,
    `- ac: ${roadmap.acJson.length} entry(ies)`,
  ];
}
