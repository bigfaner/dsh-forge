describe('task 1.2 parity — Go baseline zero diff (forge-cli pkg/task)', () => {
  it('baseline shape: 18 dep cases, 16 topo cases, 4 real indexes', () => {
    expect(baseline.depCases).toHaveLength(18)
    expect(baseline.toposortCases).toHaveLength(16)
    expect(baseline.realIndexes.map(r => r.name)).toEqual(['m1', 'm2', 'm3', 'm3-dangling'])
  })

  it('dep cases: checkTransitionDeps + getUnmetDeps match Go per case', () => {
    const failures: string[] = []
    for (const c of corpus.depCases) {
      const want = baseline.depCases.find(b => b.name === c.name)
      if (want === undefined) throw new Error(`baseline missing dep case: ${c.name}`)
      const idx = corpusIndex(c.tasks)
      const got = checkTransitionDeps(idx, c.target)
      if (JSON.stringify(sorted(got.unmet)) !== JSON.stringify(sorted(want.checkDeps?.unmet))) {
        failures.push(`${c.name} checkDeps.unmet: ${JSON.stringify(got.unmet)} != ${JSON.stringify(want.checkDeps?.unmet)}`)
      }
      if ((got.error ?? '') !== (want.checkDeps?.error ?? '')) {
        failures.push(`${c.name} checkDeps.error: ${got.error} != ${want.checkDeps?.error}`)
      }
      const deps = c.rawDeps ?? idx.byId(c.target)?.dependencies ?? []
      const gotUnmet = getUnmetDeps(idx, c.target, deps)
      if (JSON.stringify(sorted(gotUnmet)) !== JSON.stringify(sorted(want.unmet))) {
        failures.push(`${c.name} getUnmetDeps: ${JSON.stringify(gotUnmet)} != ${JSON.stringify(want.unmet)}`)
      }
    }
    expect(failures, failures.join('\n')).toEqual([])
  })

  it('toposort cases: ordered/cycles/missing match Go exactly (strict order)', () => {
    const failures: string[] = []
    for (const c of corpus.toposortCases) {
      const want = baseline.toposortCases.find(b => b.name === c.name)
      if (want === undefined) throw new Error(`baseline missing topo case: ${c.name}`)
      const got = topologicalSort(corpusIndex(c.tasks))
      if (JSON.stringify(got.ordered) !== JSON.stringify(want.ordered ?? [])) {
        failures.push(`${c.name} ordered: ${JSON.stringify(got.ordered)} != ${JSON.stringify(want.ordered)}`)
      }
      if (JSON.stringify(got.cycles) !== JSON.stringify(want.cycles ?? [])) {
        failures.push(`${c.name} cycles: ${JSON.stringify(got.cycles)} != ${JSON.stringify(want.cycles)}`)
      }
      if (JSON.stringify(got.missing) !== JSON.stringify(want.missing ?? [])) {
        failures.push(`${c.name} missing: ${JSON.stringify(got.missing)} != ${JSON.stringify(want.missing)}`)
      }
    }
    expect(failures, failures.join('\n')).toEqual([])
  })

  it('real index corpora (phase keys, T- tasks, slug keys, dangling blocker): zero diff', () => {
    const failures: string[] = []
    for (const want of baseline.realIndexes) {
      const snapshot = JSON.parse(readFileSync(new URL(`real-index-${want.name}.json`, fixturesUrl), 'utf8'))
      const idx = parseTaskIndexSnapshot(snapshot)
      const got = topologicalSort(idx)
      if (JSON.stringify(normalizeTies(got.ordered)) !== JSON.stringify(normalizeTies(want.ordered))) {
        failures.push(`${want.name} ordered head: ${JSON.stringify(got.ordered.slice(0, 5))} != ${JSON.stringify((want.ordered ?? []).slice(0, 5))}`)
      }
      if (JSON.stringify(normalizeTies(got.cycles)) !== JSON.stringify(normalizeTies(want.cycles))) failures.push(`${want.name} cycles differ`)
      if (JSON.stringify(normalizeTies(got.missing)) !== JSON.stringify(normalizeTies(want.missing))) failures.push(`${want.name} missing differ`)
      for (const [taskId, wantUnmet] of Object.entries(want.unmetByTask)) {
        const gotUnmet = getUnmetDeps(idx, taskId, idx.byId(taskId)?.dependencies)
        if (JSON.stringify(sorted(gotUnmet)) !== JSON.stringify(sorted(wantUnmet))) {
          failures.push(`${want.name} ${taskId} unmet: ${JSON.stringify(gotUnmet)} != ${JSON.stringify(wantUnmet)}`)
        }
      }
      for (const [taskId, wantCheck] of Object.entries(want.checkDepsByTask)) {
        const gotCheck = checkTransitionDeps(idx, taskId)
        if (JSON.stringify(sorted(gotCheck.unmet)) !== JSON.stringify(sorted(wantCheck.unmet))) {
          failures.push(`${want.name} ${taskId} checkDeps.unmet differs`)
        }
        if ((gotCheck.error ?? '') !== (wantCheck.error ?? '')) failures.push(`${want.name} ${taskId} checkDeps.error differs`)
      }
    }
    expect(failures, failures.join('\n')).toEqual([])
  })
})
