/** Build a TaskIndex from corpus entries (map key may differ from task ID). */
function corpusIndex(entries: readonly CorpusTaskEntry[]): TaskIndex {
  return new TaskIndex(entries.map(entry => [entry.key, entry as unknown as Task]))
}

/** Compact task literal (key defaults to the ID). */
function task(id: string, status: string, dependencies?: readonly string[], extra: Partial<Task> = {}): Task {
  return { id, status, dependencies, ...extra }
}

function index(...tasks: readonly Task[]): TaskIndex {
  return new TaskIndex(tasks.map(t => [t.id, t]))
}

const sorted = (v: readonly string[] | null | undefined): readonly string[] => [...(v ?? [])].sort()

// Tie normalization for ordered/cycles/missing: IDs that compare equal under
// the natural-order comparator (single-segment alphabetic IDs like m1's
// `fix-1`/`disc-2`/`T-review-doc` share rank (0, false)) are popped by the Go
// min-heap in MAP-ITERATION order — verified nondeterministic across
// regenerations of the Go baseline itself. Such tied neighbours therefore
// compare as an unordered run; every strictly-ordered position stays strict.
const tie = (a: string, b: string): boolean => !compareVersionIds(a, b) && !compareVersionIds(b, a)

function normalizeTies(list: readonly string[] | null | undefined): readonly string[] {
  const src = [...(list ?? [])]
  const out: string[] = []
  let run: string[] = []
  for (const id of src) {
    if (run.length === 0 || tie(run[run.length - 1] as string, id)) run.push(id)
    else {
      if (run.length > 1) run.sort()
      out.push(...run)
      run = [id]
    }
  }
  if (run.length > 1) run.sort()
  out.push(...run)
  return out
}

describe('task 1.2 model — statuses, ID dialect, natural order', () => {
  it('isTerminalStatus: completed/skipped/rejected only', () => {
    for (const status of ALL_STATUSES) {
      expect(isTerminalStatus(status), status).toBe(status === 'completed' || status === 'skipped' || status === 'rejected')
    }
  })

  it('isBusinessTask excludes T-/gate/summary IDs', () => {
    expect(isBusinessTask('1.2')).toBe(true)
    expect(isBusinessTask('1.2-statemachine-deps-port')).toBe(true)
    expect(isBusinessTask('1.gate')).toBe(false)
    expect(isBusinessTask('5.gate')).toBe(false)
    expect(isBusinessTask('1.summary')).toBe(false)
    expect(isBusinessTask('T-test-run')).toBe(false)
  })

  it('compareVersionIds: numeric segments numerically, numeric before alphabetic, gate before summary', () => {
    // strict ordering chain (each adjacent pair, plus the transitive ends)
    const chain = ['1', '1.1', '1.2', '1.10', '1.gate', '1.summary', '2', '10']
    for (let i = 0; i < chain.length - 1; i++) {
      expect(compareVersionIds(chain[i] as string, chain[i + 1] as string), `${chain[i]} < ${chain[i + 1]}`).toBe(true)
      expect(compareVersionIds(chain[i + 1] as string, chain[i] as string), `${chain[i + 1]} !< ${chain[i]}`).toBe(false)
    }
    expect(compareVersionIds('10', '9')).toBe(false)
    expect(compareVersionIds('9', '10')).toBe(true)
    expect(compareVersionIds('1.2', '1.2')).toBe(false)
    expect(compareVersionIds('1', '1.x')).toBe(true) // missing segment sorts before alphabetic
  })

  it('TaskIndex.byId: map key first, then ID fallback scan', () => {
    const idx = new TaskIndex([
      ['1.1-slug', task('1.1', 'completed')],
      ['1.2-slug', task('1.2', 'pending')],
    ])
    expect(idx.byId('1.1')?.status).toBe('completed') // ID fallback (no such key)
    expect(idx.byId('1.1-slug')?.id).toBe('1.1') // key hit
    expect(idx.byId('9.9')).toBeUndefined()
    // key precedence: key "2.1" wins over a task whose ID is "2.1"
    const prec = new TaskIndex([
      ['2.1', task('9.9', 'pending')],
      ['b', task('2.1', 'completed')],
    ])
    expect(prec.byId('2.1')?.id).toBe('9.9')
  })

  it('TaskIndex mutators: setTask + taskCount', () => {
    const idx = index(task('1.1', 'pending'))
    expect(idx.taskCount).toBe(1)
    idx.setTask('1.2-slug', task('1.2', 'blocked'))
    expect(idx.taskCount).toBe(2)
    expect(idx.byId('1.2')?.status).toBe('blocked')
  })

  it('parseTaskIndexSnapshot keeps snapshot fields verbatim', () => {
    const snap = { feature: 'f', tasks: { '1.1-s': { id: '1.1', status: 'blocked', dependencies: ['9.9'] } } }
    const idx = parseTaskIndexSnapshot(snap)
    expect(idx.byId('1.1')?.dependencies).toEqual(['9.9'])
    expect(idx.taskCount).toBe(1)
  })
})

