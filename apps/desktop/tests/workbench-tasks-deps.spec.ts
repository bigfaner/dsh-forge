describe('task 1.2 toposort — Kahn with natural-ID min-heap', () => {
  it('empty index', () => {
    const { ordered, cycles, missing } = topologicalSort(new TaskIndex())
    expect(ordered).toEqual([])
    expect(cycles).toEqual([])
    expect(missing).toEqual([])
  })

  it('same-level tasks sort by natural ID (10 after 2)', () => {
    const idx = index(task('3'), task('1'), task('2'), task('10'), task('1.1'))
    expect(topologicalSort(idx).ordered).toEqual(['1', '1.1', '2', '3', '10'])
  })

  it('M2 phase-key dialect: 1 < 1.1 < 1.2 < 1.gate < 1.summary < 2', () => {
    const idx = index(
      task('1'),
      task('1.1'),
      task('1.2'),
      task('1.gate'),
      task('1.summary'),
      task('2', 'pending', ['1.x']),
    )
    expect(topologicalSort(idx).ordered).toEqual(['1', '1.1', '1.2', '1.gate', '1.summary', '2'])
  })

  it('linear chain and diamond orders', () => {
    const chain = index(task('1'), task('2', 'pending', ['1']), task('3', 'pending', ['2']))
    expect(topologicalSort(chain).ordered).toEqual(['1', '2', '3'])
    const diamond = index(
      task('1'),
      task('2', 'pending', ['1']),
      task('3', 'pending', ['1']),
      task('4', 'pending', ['2', '3']),
    )
    expect(topologicalSort(diamond).ordered).toEqual(['1', '2', '3', '4'])
  })

  it('cycles: full cycle, self-reference, and wildcard self-edge', () => {
    const full = index(task('1', 'pending', ['3']), task('2', 'pending', ['1']), task('3', 'pending', ['2']))
    expect(topologicalSort(full)).toEqual({ ordered: [], cycles: ['1', '2', '3'], missing: [] })
    const self = index(task('1', 'pending', ['1']))
    expect(topologicalSort(self)).toEqual({ ordered: [], cycles: ['1'], missing: [] })
    // expandDeps keeps wildcard self-matches as edges (cycle detection),
    // unlike getUnmetDeps which excludes self.
    const wild = index(task('1.1', 'pending', ['1.x']), task('1.2'), task('2'))
    expect(topologicalSort(wild)).toEqual({ ordered: ['1.2', '2'], cycles: ['1.1'], missing: [] })
  })

  it('cycle members are reported alongside the healthy component', () => {
    const idx = index(
      task('1'),
      task('2', 'pending', ['1']),
      task('3', 'pending', ['4']),
      task('4', 'pending', ['3']),
    )
    expect(topologicalSort(idx)).toEqual({ ordered: ['1', '2'], cycles: ['3', '4'], missing: [] })
  })

  it('missing deps are collected and naturally sorted; the task itself still orders', () => {
    const idx = index(task('1', 'pending', ['99', '100']))
    expect(topologicalSort(idx)).toEqual({ ordered: ['1'], cycles: [], missing: ['99', '100'] })
  })

  it('unmatched wildcard is not a missing dep', () => {
    const idx = index(task('2', 'pending', ['5.x']))
    expect(topologicalSort(idx)).toEqual({ ordered: ['2'], cycles: [], missing: [] })
  })

  it('mixed exact + wildcard deps deduplicate', () => {
    const idx = index(task('1.1'), task('1.2'), task('2'), task('3', 'pending', ['1.1', '1.x']))
    expect(topologicalSort(idx).ordered).toEqual(['1.1', '1.2', '2', '3'])
  })

  it('stable across repeated runs (Go TestTopologicalSort_WildcardStability)', () => {
    const idx = index(task('1.1'), task('1.2'), task('1.3'), task('2', 'pending', ['1.x']))
    const first = JSON.stringify(topologicalSort(idx))
    for (let i = 0; i < 4; i++) expect(JSON.stringify(topologicalSort(idx))).toBe(first)
  })
})

